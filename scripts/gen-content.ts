// Generates supabase/seed/demo_seed.sql and src/demo/content.json from src/content/demoContent.ts
import fs from 'node:fs';
import { LINEUP, TASKS, TEMPLATE } from '../src/content/demoContent';

const q = (v: unknown) => `'${(typeof v === 'string' ? v : JSON.stringify(v)).replace(/'/g, "''")}'`;
const rows = TASKS.map((t) => `(${q(t.id)}, ${t.idea_no ?? 'null'}, ${q(t.kind)}, ${q(t.title)}, ${q(t.instructions)}, ${q(t.public_content)}, ${t.duration_sec}, ${q(t.scoring)}, ${t.attempts_limit}, 'captain_only', ${q(t.settings)}, ${LINEUP.includes(t.id) ? "'candidate'" : "'backup'"}, true)`);
const sql = `-- GENERATED by scripts/gen-content.ts from src/content/demoContent.ts — do not edit by hand.
-- Trial-game content (known answers). Final content is entered directly in the database, never in this repo.
insert into public.task_templates (id, idea_no, kind, title, instructions, public_content, duration_sec, scoring, attempts_limit, submission_policy, settings, status, is_placeholder) values
${rows.join(',\n')}
on conflict (id) do update set idea_no = excluded.idea_no, kind = excluded.kind, title = excluded.title, instructions = excluded.instructions,
  public_content = excluded.public_content, duration_sec = excluded.duration_sec, scoring = excluded.scoring, attempts_limit = excluded.attempts_limit,
  settings = excluded.settings, status = excluded.status, is_placeholder = excluded.is_placeholder, updated_at = now();

insert into private.task_secrets (task_id, answer_key, verified_note) values
${TASKS.map((t) => `(${q(t.id)}, ${q(t.answer_key)}, 'trial content')`).join(',\n')}
on conflict (task_id) do update set answer_key = excluded.answer_key, verified_note = excluded.verified_note;

insert into public.game_templates (id, name, settings, is_placeholder) values (${q(TEMPLATE.id)}, ${q(TEMPLATE.name)}, ${q(TEMPLATE.settings)}, true)
on conflict (id) do update set name = excluded.name, settings = excluded.settings;

delete from public.game_template_rounds where template_id = ${q(TEMPLATE.id)};
insert into public.game_template_rounds (template_id, round_no, task_id) values
${LINEUP.map((id, i) => `(${q(TEMPLATE.id)}, ${i + 1}, ${q(id)})`).join(',\n')};
`;
fs.writeFileSync('supabase/seed/demo_seed.sql', sql);
const json = {
  tasks: TASKS.map(({ answer_key, idea_no, ...t }) => ({ ...t, assets: [], submission_policy: 'captain_only' })),
  secrets: Object.fromEntries(TASKS.map((t) => [t.id, t.answer_key])),
  template: TEMPLATE,
  rounds: LINEUP.map((task_id, i) => ({ round_no: i + 1, task_id })),
};
fs.writeFileSync('src/demo/content.json', JSON.stringify(json));
console.log('seed + content.json written:', TASKS.length, 'tasks');
